// Generates src/content_gen.lua and src/strings_gen.lua from the web game's own JS,
// so every number and every DA/EN string is copied by a machine, not retyped.
// Usage: node tools/gen_content.js [folder containing js/data.js]  (default: the web game one folder up, so there is no copy to keep in sync)
// The web folder is only READ.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { hookHash } from './hookhash.mjs';

const src = path.resolve(process.argv[2] || path.join(import.meta.dirname, '..', '..'));
const jsDir = fs.existsSync(path.join(src, 'js')) ? path.join(src, 'js') : src;
const out = path.resolve(import.meta.dirname, '..', 'src');
const D = await import(pathToFileURL(path.join(jsDir, 'data.js')).href);

const q = s => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;
function lua(v, ind = '') {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'nil';
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return q(v);
  if (Array.isArray(v)) return '{' + v.map(x => lua(x, ind)).join(', ') + '}';
  const ks = Object.keys(v).filter(k => typeof v[k] !== 'function');
  const i2 = ind + '  ';
  return '{\n' + ks.map(k => `${i2}${/^[1-9][0-9]*$/.test(k) ? '[' + k + ']' : IDENT.test(k) && !['end', 'and', 'or', 'not', 'if', 'then', 'else', 'for', 'in', 'do', 'while', 'function', 'local', 'return', 'nil', 'true', 'false', 'repeat', 'until', 'break', 'goto', 'elseif'].includes(k) ? k : '[' + q(k) + ']'} = ${lua(v[k], i2)},`).join('\n') + '\n' + ind + '}';
}

let o = '-- GENERATED by tools/gen_content.js from the web game\'s js/data.js. Do not edit by hand.\n';
o += 'local M = {}\n';
const emit = (name, obj) => { o += `M.${name} = ${lua(obj)}\n`; };
emit('LINE_TYPES', D.LINE_TYPES);
emit('LINE_ORDER', D.LINE_ORDER);
emit('PIECES', D.PIECES);
emit('PIECES_ORDER', Object.keys(D.PIECES));
emit('SPECIALS', D.SPECIALS);
emit('TILES', Object.fromEntries(Object.entries(D.TILES).map(([k, v]) => [k, { name: v.name, desc: v.desc }])));
emit('TILES_ORDER', Object.keys(D.TILES));
emit('RARITY', D.RARITY);
const jk = {};
for (const [k, j] of Object.entries(D.JOKERS)) {
  jk[k] = { name: j.name, rar: j.rar, cost: j.cost, gl: j.gl, desc: j.desc({ data: {} }), hasReq: !!j.req, hasLine: !!j.line, hasX: !!j.x, hasEnd: !!j.endRound, hasVal: !!j.val };
}
emit('JOKERS', jk);
emit('JOKERS_ORDER', Object.keys(D.JOKERS));
emit('HOOK_HASH', Object.fromEntries(Object.entries(D.JOKERS).map(([k, j]) => [k, hookHash(j)])));
emit('EDITIONS', D.EDITIONS);
emit('EDITIONS_ORDER', Object.keys(D.EDITIONS));
emit('PACKS', D.PACKS);
emit('PACKS_ORDER', Object.keys(D.PACKS));
emit('ITEMS', D.ITEMS);
emit('ITEMS_ORDER', Object.keys(D.ITEMS));
emit('VOUCHERS', Object.fromEntries(Object.entries(D.VOUCHERS).map(([k, v]) => [k, { name: v.name, gl: v.gl, desc: v.desc, hasReq: !!v.req }])));
emit('VOUCHERS_ORDER', Object.keys(D.VOUCHERS));
emit('BOSSES', D.BOSSES);
emit('BOSSES_ORDER', Object.keys(D.BOSSES));
emit('ANTE_BASE', D.ANTE_BASE);
o += 'return M\n';
fs.writeFileSync(path.join(out, 'content_gen.lua'), o);

// strings.js does not export its dictionaries, so slice the two object literals out.
const sj = fs.readFileSync(path.join(jsDir, 'strings.js'), 'utf8');
const grab = name => {
  const a = sj.indexOf(`const ${name} = {`);
  const b = sj.indexOf('\n};', a);
  return (0, eval)('(' + sj.slice(a + `const ${name} = `.length, b + 3).replace(/;$/, '') + ')');
};
const EN = grab('EN'), DA = grab('DA');
let s = '-- GENERATED by tools/gen_content.js from the web game\'s js/strings.js. Do not edit by hand.\nlocal M = {}\n';
s += `M.EN = ${lua(EN)}\nM.DA = ${lua(DA)}\nreturn M\n`;
fs.writeFileSync(path.join(out, 'strings_gen.lua'), s);
console.log('jokers', Object.keys(D.JOKERS).length, 'EN keys', Object.keys(EN).length, 'DA keys', Object.keys(DA).length);
